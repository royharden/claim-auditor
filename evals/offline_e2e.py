"""Exercise packaged CLI on its owned public demo, retain output and test tamper refusal."""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

from claim_auditor.contracts import canonical_json, sha256


def exercise(out: Path):
    out.mkdir(parents=True, exist_ok=False)
    commands = []

    def run(arguments, expected):
        command = [sys.executable, "-I", "-m", "claim_auditor", *map(str, arguments)]
        completed = subprocess.run(command, capture_output=True, timeout=150, check=False)
        index = len(commands)
        (out / f"command-{index}.stdout").write_bytes(completed.stdout)
        (out / f"command-{index}.stderr").write_bytes(completed.stderr)
        commands.append({"argv": command, "exit": completed.returncode, "expected_exit": expected,
                         "stdout_sha256": sha256(completed.stdout), "stderr_sha256": sha256(completed.stderr)})
        if completed.returncode != expected:
            (out / "E2E.json").write_bytes(canonical_json({"status": "failed", "commands": commands}) + b"\n")
            raise AssertionError(f"{arguments[0]} returned {completed.returncode}, expected {expected}: {completed.stderr.decode(errors='replace')}")
        return completed

    demo = out / "demo"
    run(["demo", "--offline", "--out", demo], 0)
    run(["verify-report", demo / "run"], 0)
    manifest = json.loads((demo / "run" / "RUN.json").read_bytes())
    if manifest["mode"] != "rules" or manifest["attempts"]:
        raise AssertionError("Offline demo must remain rules-only with no physical provider attempts")
    # Only mutate a file generated by this invocation. Retain every artifact.
    frozen = list((demo / "snapshot").rglob("README.md"))
    if len(frozen) != 1:
        raise AssertionError(f"Expected one owned frozen README, found {frozen}")
    target = frozen[0]
    before = sha256(target.read_bytes())
    target.write_bytes(target.read_bytes() + b"\nRV2-owned tamper sentinel\n")
    tamper = run(["verify-report", demo / "run"], 4)
    result = {"status": "passed", "designation": "PUBLIC_OFFLINE_CLI_E2E", "provider_calls": 0,
              "human_adjudicated": False, "comparative_complete": False,
              "commands": commands, "tampered_path": str(target), "original_sha256": before,
              "tampered_sha256": sha256(target.read_bytes()),
              "tamper_refusal": tamper.stdout.decode(errors="replace"),
              "not_measured": ["human-adjudicated benchmark", "live arms", "heldout", "Action"]}
    (out / "E2E.json").write_bytes(canonical_json(result) + b"\n")
    print(json.dumps({"status": "passed", "commands": len(commands), "provider_calls": 0}))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    exercise(args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
